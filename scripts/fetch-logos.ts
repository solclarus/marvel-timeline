// Fetches every work's English title logo from TMDB and rewrites
// `src/data/logos.ts`. English in every language, so the map reads the same
// everywhere. A season uses its show's logo. A logo already chosen stays
// while TMDB still lists it (TMDB's order changes with its users' votes);
// otherwise the best-voted one is taken. Needs a TMDB API read access
// token, from the environment or `.env.local` (TMDB_TOKEN=...):
// pnpm fetch:logos
import { writeFileSync } from "node:fs";

import { LOGOS } from "../src/data/logos.ts";
import { WORKS, type WorkNode } from "../src/data/works.ts";

const token = process.env.TMDB_TOKEN;
if (!token) {
  console.error("Set TMDB_TOKEN to a TMDB API read access token (themoviedb.org/settings/api).");
  process.exit(2);
}

interface Logo {
  file_path: string;
  iso_639_1: string | null;
}

async function englishLogo(work: WorkNode): Promise<string | null> {
  const { type, id } = work.tmdb;
  const path = `/${type === "movie" ? "movie" : "tv"}/${id}/images?include_image_language=en`;
  const response = await fetch(`https://api.themoviedb.org/3${path}`, {
    headers: { Authorization: `Bearer ${token}`, Accept: "application/json" },
  });
  if (response.status === 404) return null;
  if (!response.ok) throw new Error(`${path}: HTTP ${response.status}`);
  const { logos = [] } = (await response.json()) as { logos?: Logo[] };
  const english = logos.filter((logo) => logo.iso_639_1 === "en").map((logo) => logo.file_path);
  const current = LOGOS[work.id];
  if (current && english.includes(current)) return current;
  // TMDB lists the best-voted first.
  return english[0] ?? null;
}

const logos = new Map<string, string>();
const failures: string[] = [];
// A few at a time, well under TMDB's rate limit.
const BATCH = 8;
for (let i = 0; i < WORKS.length; i += BATCH) {
  await Promise.all(
    WORKS.slice(i, i + BATCH).map(async (work) => {
      try {
        const logo = await englishLogo(work);
        if (logo) logos.set(work.id, logo);
      } catch (error) {
        failures.push(`${work.id}: ${(error as Error).message}`);
      }
    }),
  );
}
if (failures.length > 0) {
  for (const failure of failures) console.error(`failed  ${failure}`);
  process.exit(1);
}

// In the works' own order, so diffs stay readable.
const entries = WORKS.filter((w) => logos.has(w.id)).map(
  (w) => `  "${w.id}": "${logos.get(w.id)}",`,
);
writeFileSync(
  new URL("../src/data/logos.ts", import.meta.url),
  `// Generated by \`pnpm fetch:logos\` from TMDB; don't edit by hand. Each work's
// English title logo (a season uses its show's); works TMDB has none for yet
// are left out.
export const LOGOS: Record<string, string> = {
${entries.join("\n")}
};
`,
);
console.log(`${logos.size} of ${WORKS.length} works have a logo`);
