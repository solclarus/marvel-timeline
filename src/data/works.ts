export type EdgeKind = "direct-sequel" | "spin-off" | "leads-into" | "crossover" | "reference";

// "reference" is excluded — a loose cameo tie isn't a prerequisite.
export const HARD_EDGE_KINDS: readonly EdgeKind[] = [
  "direct-sequel",
  "spin-off",
  "leads-into",
  "crossover",
];

// Where `releaseDate` and `poster` come from: themoviedb.org/movie/<id> or
// /tv/<id>/season/<season>.
interface TmdbRef {
  type: "movie" | "tv";
  id: number;
  season?: number; // tv only: which season's poster and air date to use
}

interface Dependency {
  id: string;
  kind: EdgeKind;
}

export interface WorkNode {
  id: string;
  title: string;
  // Japanese title, from TMDB's ja-JP listing where it has one.
  titleJa: string;
  franchise: Franchise;
  // Animated, whether a film or a series; see `mediumOf`.
  animated?: true;
  // MCU only.
  phase?: number;
  // MCU only: keeps a character line in one lane through ensemble films.
  thread?: string;
  // Overrides FRANCHISE_META[franchise].earth. The first is the work's home
  // Earth; any others are Earths it crosses into. See `earthsOf`.
  earths?: EarthId[];
  dependsOn?: Dependency[];
  chronologyOrder: number;
  setYear?: number;
  recommendedOrder: number | null;
  tmdb: TmdbRef;
  releaseDate: string;
  // Only the month or year is announced; `releaseDate` holds its first day.
  releasePrecision?: "month" | "year";
  // TMDB poster path, e.g. "/abc.jpg" — see `posterUrl`; "" while TMDB has
  // none, which shows stand-in art.
  poster: string;
}

// What kind of work it is, for the media filter: animation wins over the
// film/series split, so an animated film counts as animation.
export type Medium = "movie" | "series" | "animation";
export const MEDIA: readonly Medium[] = ["movie", "series", "animation"];

export function mediumOf(work: WorkNode): Medium {
  if (work.animated) return "animation";
  return work.tmdb.type === "movie" ? "movie" : "series";
}

// Whether a work is still to come, by the viewer's clock.
export function isUpcoming(work: WorkNode, today = new Date()): boolean {
  const local = new Date(today.getTime() - today.getTimezoneOffset() * 60_000);
  return work.releaseDate > local.toISOString().slice(0, 10);
}

export interface WorkEdge {
  from: string;
  to: string;
  kind: EdgeKind;
}

